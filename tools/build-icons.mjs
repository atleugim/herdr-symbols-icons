#!/usr/bin/env node
// Regenerates mods/symbols-icons/icons/ and mods/symbols-icons/icons.js from Miguel Solorio's
// Symbols icon theme (MIT, https://github.com/miguelsolorio/vscode-symbols).
//
//   node tools/build-icons.mjs [git ref]     default: the commit pinned below
//
// Needs node 18+ and tar. Writes only inside mods/symbols-icons/.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, rmSync, mkdirSync, copyFileSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const REF = process.argv[2] ?? "2c95b15b0a8ef95ac62855e3784a6024ee6e5d2e";
const MOD = join(dirname(fileURLToPath(import.meta.url)), "..", "mods", "symbols-icons");
const ICONS = join(MOD, "icons");

// The theme maps some extensions only through VS Code's language ids, which the panel can't see.
// These are the extensions VS Code gives those languages; a real fileExtensions entry wins.
const LANGUAGE_EXTENSIONS = {
  php: ["php", "phtml", "php3", "php4", "php5", "phps"],
  vue: ["vue"],
  haskell: ["hs", "lhs"],
  elixir: ["ex", "exs"],
  erlang: ["erl", "hrl"],
  scala: ["scala", "sc"],
  dart: ["dart"],
  clojure: ["clj", "cljs", "cljc", "edn"],
  coffeescript: ["coffee", "cson"],
  fsharp: ["fs", "fsi", "fsx"],
  csharp: ["cs", "csx"],
  razor: ["cshtml", "razor"],
  perl: ["pl", "pm", "pod", "t"],
  r: ["r", "rhistory", "rprofile"],
  graphql: ["graphql", "gql"],
  pug: ["pug", "jade"],
  properties: ["properties", "cfg", "conf", "ini"],
  less: ["less"],
  sass: ["sass"],
  scss: ["scss"],
  stylus: ["styl"],
  tex: ["tex", "ltx", "sty", "cls"],
  julia: ["jl"],
  crystal: ["cr"],
  nix: ["nix"],
  terraform: ["tf", "tfvars"],
  swift: ["swift"],
  handlebars: ["hbs", "handlebars"],
  twig: ["twig"],
  haml: ["haml"],
  "objective-c": ["m"],
  "objective-cpp": ["mm"],
  powershell: ["ps1", "psm1", "psd1"],
  makefile: ["mk", "mak"],
  dockerfile: ["dockerfile", "containerfile"],
};
const LANGUAGE_FILE_NAMES = { makefile: ["makefile", "gnumakefile"], dockerfile: ["dockerfile", "containerfile"] };

const tmp = mkdtempSync(join(tmpdir(), "symbols-icons-"));
try {
  const res = await fetch(`https://codeload.github.com/miguelsolorio/vscode-symbols/tar.gz/${REF}`);
  if (!res.ok) throw new Error(`download failed: ${res.status} ${res.statusText}`);
  writeFileSync(join(tmp, "src.tgz"), Buffer.from(await res.arrayBuffer()));
  execFileSync("tar", ["xzf", "src.tgz"], { cwd: tmp });
  const repo = join(tmp, readdirSync(tmp).find(name => name !== "src.tgz"));
  const manifest = JSON.parse(readFileSync(join(repo, "src", "symbol-icon-theme.json"), "utf8"));
  const defs = manifest.iconDefinitions;
  const languages = manifest.languageIds ?? {};

  // VS Code matches names case-insensitively.
  const lower = (map = {}) => Object.fromEntries(Object.entries(map).map(([k, v]) => [k.toLowerCase(), v]));
  function fromLanguages(table, extra) {
    const out = {};
    for (const [lang, keys] of Object.entries(extra)) {
      const id = languages[lang];
      if (id) for (const k of keys) out[k] = id;
    }
    return { ...out, ...table };
  }

  const data = {
    file: manifest.file,
    folder: manifest.folder,
    fileNames: fromLanguages(lower(manifest.fileNames), LANGUAGE_FILE_NAMES),
    fileExtensions: fromLanguages(lower(manifest.fileExtensions), LANGUAGE_EXTENSIONS),
    folderNames: lower(manifest.folderNames),
  };

  const used = new Set([data.file, data.folder]);
  for (const table of [data.fileNames, data.fileExtensions, data.folderNames]) for (const id of Object.values(table)) used.add(id);
  const missing = [...used].filter(id => !defs[id]);
  if (missing.length) throw new Error(`theme names icons it does not define: ${missing.join(", ")}`);

  rmSync(ICONS, { recursive: true, force: true });
  mkdirSync(ICONS, { recursive: true });
  for (const id of [...used].sort()) copyFileSync(join(repo, "src", defs[id].iconPath), join(ICONS, `${id}.svg`));
  copyFileSync(join(repo, "LICENSE"), join(MOD, "LICENSE-symbols.txt"));

  writeFileSync(join(MOD, "icons.js"),
    `// Generated by tools/build-icons.mjs from vscode-symbols ${REF} (MIT). Do not edit.\n` +
    `export default ${JSON.stringify(data)};\n`);
  console.log(`vscode-symbols ${REF.slice(0, 12)}: ${readdirSync(ICONS).length} icons, ` +
    `${Object.keys(data.fileNames).length} file names, ${Object.keys(data.fileExtensions).length} extensions, ` +
    `${Object.keys(data.folderNames).length} folder names → ${basename(MOD)}/`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
